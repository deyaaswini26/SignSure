'''SignSure Streamlit entry point.

Provides a light‑themed dashboard with four pages:
- Dashboard (overview + stats)
- Sign Document (upload, sign, download)
- Verify Document (upload signed ZIP, verify, trust status)
- About (explanation of cryptographic concepts)
''' 

from __future__ import annotations

import pathlib
import streamlit as st

# Initialise the database (creates tables if missing)
from app import db

db.init_db()

# Import UI modules lazily so Streamlit only loads what is needed
from app.ui import sign_document, verify_document

# ---------------------------------------------------------------------------
# Page layout helpers
# ---------------------------------------------------------------------------

def _dashboard_page() -> None:
    """Show a simple dashboard with project description and stats."""
    st.title("SignSure – Intelligent Digital Signature Verification System")
    st.markdown(
        """
        **Welcome!**  SignSure demonstrates how RSA‑2048 keys, SHA‑256 hashing, and RSA‑PSS signatures can be used to protect PDF documents.
        
        Use the sidebar to navigate between pages.
        """
    )
    # Retrieve statistics from the DB (if any)
    try:
        stats = db.get_stats()
        st.subheader("Current statistics")
        col1, col2, col3 = st.columns(3)
        col1.metric("Signed documents", stats.get("total_documents", 0))
        col2.metric("Verification attempts", stats.get("total_verifications", 0))
        col3.metric("Trusted signers", stats.get("trusted_signers", 0))
    except Exception as e:
        st.warning(f"Unable to load statistics: {e}")


def _about_page() -> None:
    """Static page explaining the cryptographic concepts."""
    st.title("About SignSure")
    st.markdown(
        """
        **What is signed?**
        
        - **RSA‑2048** – an asymmetric key pair. The private key signs, the public key verifies.
        - **SHA‑256** – a cryptographic hash function; the document’s exact bytes are reduced to a 256‑bit digest.
        - **RSA‑PSS** – a modern padding scheme (MGF1 + SHA‑256) that provides provable security for signatures.
        
        **Important security notes**
        
        - A digital signature guarantees *integrity* and *authenticity* but does **not** encrypt the document.
        - The public key bundled inside a signed package does **not** establish the signer’s identity.
        - Trust is managed separately via the *trusted‑signer registry* in the SQLite database.
        - QR codes generated by the application contain only a verification ID; they are merely a lookup token.
        """
    )

# ---------------------------------------------------------------------------
# Streamlit app execution
# ---------------------------------------------------------------------------

st.set_page_config(page_title="SignSure", layout="centered", page_icon="🖋️")

# Sidebar navigation
page = st.sidebar.selectbox(
    "Navigate",
    ("Dashboard", "Sign Document", "Verify Document", "About"),
    index=0,
)

if page == "Dashboard":
    _dashboard_page()
elif page == "Sign Document":
    sign_document.render()
elif page == "Verify Document":
    verify_document.render()
elif page == "About":
    _about_page()

